-- Dem dong thuc te cua 12 bang sau khi import.
-- So lieu tham chieu tu lan kiem tra nguon va export.log ngay 08/11/2026:
-- BRANDS 10; CATEGORIES 8; COLORS 8; CUSTOMERS 12; EMPLOYEES 8;
-- ORDERDETAILS 46; ORDERS 30; PAYMENTS 28; PRODUCTS 130;
-- PRODUCTVARIANTS 1300; SIZES 9; SUPPLIERS 5.
-- Cac COUNT duoi day la so thuc te tai thoi diem chay, khong phai so lieu ghi cung.

SELECT 'BRANDS' AS table_name, COUNT(*) AS row_count FROM BTL_GIAYTHETHAO.BRANDS
UNION ALL SELECT 'CATEGORIES', COUNT(*) FROM BTL_GIAYTHETHAO.CATEGORIES
UNION ALL SELECT 'COLORS', COUNT(*) FROM BTL_GIAYTHETHAO.COLORS
UNION ALL SELECT 'CUSTOMERS', COUNT(*) FROM BTL_GIAYTHETHAO.CUSTOMERS
UNION ALL SELECT 'EMPLOYEES', COUNT(*) FROM BTL_GIAYTHETHAO.EMPLOYEES
UNION ALL SELECT 'ORDERDETAILS', COUNT(*) FROM BTL_GIAYTHETHAO.ORDERDETAILS
UNION ALL SELECT 'ORDERS', COUNT(*) FROM BTL_GIAYTHETHAO.ORDERS
UNION ALL SELECT 'PAYMENTS', COUNT(*) FROM BTL_GIAYTHETHAO.PAYMENTS
UNION ALL SELECT 'PRODUCTS', COUNT(*) FROM BTL_GIAYTHETHAO.PRODUCTS
UNION ALL SELECT 'PRODUCTVARIANTS', COUNT(*) FROM BTL_GIAYTHETHAO.PRODUCTVARIANTS
UNION ALL SELECT 'SIZES', COUNT(*) FROM BTL_GIAYTHETHAO.SIZES
UNION ALL SELECT 'SUPPLIERS', COUNT(*) FROM BTL_GIAYTHETHAO.SUPPLIERS
ORDER BY table_name;
