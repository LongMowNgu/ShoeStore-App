-- Run this script while connected to the Oracle application schema (not SYS/SYSTEM).
-- It creates the identity, role, employee, shoe-style and shoe-variant foundation.
-- Re-running the script is safe when the objects already exist.
BEGIN EXECUTE IMMEDIATE 'CREATE TABLE EMPLOYEE (
    EMPLOYEE_ID NUMBER(10) CONSTRAINT PK_EMPLOYEE PRIMARY KEY,
    FULL_NAME NVARCHAR2(100) NOT NULL,
    PHONE VARCHAR2(20),
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0,1))
)'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/
BEGIN EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_EMPLOYEE START WITH 1 INCREMENT BY 1 NOCACHE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/
BEGIN EXECUTE IMMEDIATE 'CREATE TABLE APP_USER (
    USER_ID NUMBER(10) CONSTRAINT PK_APP_USER PRIMARY KEY,
    USERNAME VARCHAR2(40) NOT NULL,
    PASSWORD_HASH VARCHAR2(100) NOT NULL,
    PASSWORD_SALT VARCHAR2(100) NOT NULL,
    ROLE_CODE VARCHAR2(20) NOT NULL CHECK (ROLE_CODE IN (''MANAGER'',''CASHIER'',''WAREHOUSE'')),
    EMPLOYEE_ID NUMBER(10) UNIQUE REFERENCES EMPLOYEE(EMPLOYEE_ID),
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0,1)),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_APP_USER_USERNAME UNIQUE (USERNAME),
    CONSTRAINT CK_APP_USER_EMPLOYEE CHECK (ROLE_CODE = ''MANAGER'' OR EMPLOYEE_ID IS NOT NULL)
)'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/
BEGIN EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_APP_USER START WITH 1 INCREMENT BY 1 NOCACHE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/
BEGIN EXECUTE IMMEDIATE 'CREATE TABLE SHOE_STYLE (
    STYLE_ID NUMBER(10) CONSTRAINT PK_SHOE_STYLE PRIMARY KEY,
    STYLE_NAME NVARCHAR2(150) NOT NULL,
    BRAND NVARCHAR2(80) NOT NULL,
    CATEGORY NVARCHAR2(60),
    DESCRIPTION NVARCHAR2(1000),
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0,1))
)'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/
BEGIN EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_SHOE_STYLE START WITH 1 INCREMENT BY 1 NOCACHE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/
BEGIN EXECUTE IMMEDIATE 'CREATE TABLE SHOE_VARIANT (
    VARIANT_ID NUMBER(10) CONSTRAINT PK_SHOE_VARIANT PRIMARY KEY,
    STYLE_ID NUMBER(10) NOT NULL REFERENCES SHOE_STYLE(STYLE_ID),
    SKU VARCHAR2(40) NOT NULL,
    SIZE_CODE VARCHAR2(10) NOT NULL,
    COLOR NVARCHAR2(40) NOT NULL,
    SELL_PRICE NUMBER(12,2) DEFAULT 0 NOT NULL CHECK (SELL_PRICE >= 0),
    STOCK_QTY NUMBER(10) DEFAULT 0 NOT NULL CHECK (STOCK_QTY >= 0),
    REORDER_LEVEL NUMBER(10) DEFAULT 3 NOT NULL CHECK (REORDER_LEVEL >= 0),
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0,1)),
    CONSTRAINT UQ_SHOE_VARIANT_SKU UNIQUE (SKU),
    CONSTRAINT UQ_SHOE_VARIANT_SIZE_COLOR UNIQUE (STYLE_ID, SIZE_CODE, COLOR)
)'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/
BEGIN EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_SHOE_VARIANT START WITH 1 INCREMENT BY 1 NOCACHE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/
-- Roles are application roles stored in APP_USER. Do not use Oracle SYS/SYSTEM credentials in the app.
