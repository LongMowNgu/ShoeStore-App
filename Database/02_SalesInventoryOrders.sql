-- Run after 01_Schema.sql, connected to the application schema in its PDB.
-- Idempotent Oracle DDL for sales, receiving, stock history, online orders and reports.
DECLARE v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME='SHOE_VARIANT' AND COLUMN_NAME='COST_PRICE';
  IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE SHOE_VARIANT ADD (COST_PRICE NUMBER(12,2) DEFAULT 0 NOT NULL CHECK (COST_PRICE >= 0))'; END IF;
END;
/
