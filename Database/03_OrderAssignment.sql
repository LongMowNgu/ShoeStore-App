-- Apply after 01_Schema.sql and 02_SalesInventoryOrders.sql.
-- Adds employee assignment to online orders; safe to rerun.
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME='ONLINE_ORDER' AND COLUMN_NAME='ASSIGNED_TO_USER_ID';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE ONLINE_ORDER ADD (ASSIGNED_TO_USER_ID NUMBER(10))'; END IF;
    SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS WHERE TABLE_NAME='ONLINE_ORDER' AND CONSTRAINT_NAME='FK_ONLINE_ORDER_ASSIGNEE';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE ONLINE_ORDER ADD CONSTRAINT FK_ONLINE_ORDER_ASSIGNEE FOREIGN KEY (ASSIGNED_TO_USER_ID) REFERENCES APP_USER(USER_ID)'; END IF;
END;
/
